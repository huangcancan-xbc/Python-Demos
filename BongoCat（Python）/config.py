"""邦戈猫 Python 版 - 配置文件

本模块定义了程序运行所需的全部常量和映射关系。

主要内容：
    - 资源路径配置（图片、音效）
    - 窗口尺寸与帧率
    - 亮色/暗色主题颜色方案
    - 乐器名称定义（中英文映射）
    - 键盘按键到乐器音效的映射表
    - 鼠标按键映射
"""

from pathlib import Path

# ── 资源路径 ────────────────────────────────────────────────────────────
# 所有素材（图片、音效）均位于本项目目录下的 images/ 和 sounds/ 文件夹中，
# 确保整个项目文件夹可以独立迁移而不丢失资源引用。

BASE_DIR = Path(__file__).parent          # 本文件所在目录（项目根目录）
ASSET_DIR = BASE_DIR / "images"           # 精灵图资源目录
SOUND_DIR = BASE_DIR / "sounds"           # 音效文件资源目录

# ── 显示配置 ────────────────────────────────────────────────────────────
# 窗口尺寸 800x600，比原版网页版（800x450）更高，
# 以完整展示猫咪精灵图并为顶部/底部 UI 面板留出空间。
# SPRITE_Y 是精灵图绘制时的 Y 轴偏移，将猫咪居中显示。

WIDTH, HEIGHT = 800, 600     # 窗口宽度、高度（像素）
SPRITE_Y = 60                # 精灵图 Y 偏移（为顶部 UI 留空间）
FPS = 60                     # 目标帧率

# ── 亮色主题 ────────────────────────────────────────────────────────────
BG_LIGHT    = (245, 245, 245)    # 浅灰色背景
TEXT_LIGHT  = (60, 60, 60)       # 深灰色文字
PANEL_LIGHT = (220, 220, 220)    # 浅灰色面板背景

# ── 暗色主题 ────────────────────────────────────────────────────────────
BG_DARK     = (40, 40, 40)       # 深灰色背景
TEXT_DARK   = (200, 200, 200)    # 浅灰色文字
PANEL_DARK  = (55, 55, 55)       # 深灰色面板背景

# ── 乐器定义 ────────────────────────────────────────────────────────────
# 保留 4 种核心乐器：邦戈鼓、钢琴、铃鼓、喵叫。
# 每种乐器对应一组音效文件和一个可显示的精灵图覆盖层（喵叫除外）。

INSTRUMENTS = ("bongo", "keyboard", "tambourine", "meow")

# 乐器的中文名称（用于界面显示）
INSTRUMENT_CN = {
    "bongo":      "邦戈鼓",
    "keyboard":   "钢琴",
    "tambourine": "铃鼓",
    "meow":       "喵叫",
}

# ── 按键映射 ────────────────────────────────────────────────────────────
# KEY_MAP 将键盘按键映射到 (乐器名称, 音效索引)。
# 例如按 "a" 键 → 播放邦戈鼓的第 1 个音效（左击）。
#
# LEFT_PAW_KEYS 定义了哪些按键触发左爪动画，
# 其余按键触发右爪，空格键触发嘴巴（喵叫）。

LEFT_PAW_KEYS = {"a", "1", "2", "3", "4", "5"}

KEY_MAP = {
    # 邦戈鼓：A = 左击，D = 右击
    "a": ("bongo", 1), "d": ("bongo", 0),
    # 钢琴：数字行 1-0 对应 keyboard0 ~ keyboard9 共 10 个音阶
    "1": ("keyboard", 0), "2": ("keyboard", 1), "3": ("keyboard", 2),
    "4": ("keyboard", 3), "5": ("keyboard", 4), "6": ("keyboard", 5),
    "7": ("keyboard", 6), "8": ("keyboard", 7), "9": ("keyboard", 8),
    "0": ("keyboard", 9),
    # 铃鼓
    "b": ("tambourine", 0),
    # 喵叫（空格键）
    "space": ("meow", 0),
}

# 每种乐器在界面顶部显示的可用按键提示
KEY_HINTS = {
    "bongo":      "A / D",
    "keyboard":   "1 2 3 4 5 6 7 8 9 0",
    "tambourine": "B",
    "meow":       "空格",
}

# 鼠标按键映射：pygame 按键编号 → 虚拟按键字符串
# 1 = 左键（邦戈左击），2 = 中键（喵叫），3 = 右键（邦戈右击）
MOUSE_MAP = {1: "a", 2: "space", 3: "d"}
